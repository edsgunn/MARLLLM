#!/usr/bin/env python3
"""
C7 — MEASURE THE CORRECTION NEEDED TO USE A GENERATOR'S LOG-PROBS AS p_env.

    NOT YET RUN. Needs a GPU scoring pass: no logged artefact carries per-token
    log-probabilities. Written now so the falsification conditions are fixed
    before any number exists (PROCESS.md).

WHAT THIS CHANGES
    The main derivation drops Sum_s sigma_s ln p_env(x_s | x_<s) because p_env
    "is only ever sampled, not evaluated". In a population that is false for the
    only observation tokens carrying entropy — other agents' posts, generated by
    adapters we hold. environment_likelihood_derivation.md works out what
    recovering them costs. This measures it.

    The derivation's result: p_env is OBSERVER-INDEPENDENT under full
    observability, and the single correction is to marginalise the GENERATOR's
    private prefix. Exactly (eq. 2):

        ln p_env(y | u)  =  ln p_theta_j(y | u, z*)  -  i(z*; y | u)

    with E[i] = I(z; y | u) >= 0, zero iff the post is conditionally independent
    of the private prefix.

WHAT WE EXPECT TO LEARN
    The size of I(z; y | u) per delivered post, by substrate and checkpoint, and
    hence whether the naive cross-agent substitution is good enough to use as-is.

    Estimator, per post y_s by generator j:
        1. rebuild u_s as j saw it, with j's private prefix removed
        2. draw K fresh private prefixes z^(k) ~ p_theta_j(. | u_s, c_j)
        3. score l_k = ln p_theta_j(y_s | u_s, c_j, z^(k))
        4. ln p_env_hat = logsumexp_k(l_k) - ln K
        5. beta_hat = ln p_theta_j(y_s | u_s, c_j, z*) - ln p_env_hat

    ln p_env_hat is downward-biased by O(1/K) through Jensen, so beta_hat is an
    UPPER estimate and small K errs toward overstating the correction. Draw z^(k)
    from the prior; including z* biases toward the realised sample.

    Scoring is at the STRING level under each model's own tokenisation
    (derivation section 6). Do not attempt per-token alignment: B5 shows the
    generator's and observer's token sequences differ for the same string.

PRE-REGISTERED PREDICTIONS, AND WHAT WOULD FALSIFY EACH
    P1  beta_hat ~ 0 at early checkpoints, where the pre-post region is 0-2
        tokens (B6). FALSIFIED IF large there — that would mean the latent is
        not the non-post region and the derivation's section 4.1(c) is wrong.
    P2  beta_hat grows with pre-post length: largest late on inner_loop (232
        tokens) and margin_notes (162), smaller on ashbourne_gc (35).
        FALSIFIED IF no relationship — the post would not depend on the private
        prefix at all, and private deliberation would be inert.
    P3  beta_hat <= H(y | u), the per-span entropy, since I <= H is a theorem.
        A violation is an estimator or alignment error, not a finding.
    P4  the estimate is identical for every observer of the same post.
        FALSIFIED IF observer-dependent on a forum substrate — that contradicts
        the conditional-independence argument and would point at a channel we
        have not accounted for.

    STRATIFY by whether the realised private region is degenerate. B6 finds
    8-11% of late generations have token-loop private regions; a loop predicts
    more loop, so those spans will show large I for an uninteresting reason.
    Reported separately or the aggregate misleads.

WHAT THIS CANNOT SETTLE
    Anything about `social_terminal`. Under fog of war the public thread differs
    between observers, the conditional-independence argument fails, and p_env
    genuinely IS observer-specific. This script asserts full observability and
    refuses substrates that do not have it.

    It also does not test the corrected OBJECTIVE — only the size of the
    correction to the estimate. Training under the restored return is C5, and
    its risk is separate: the corrected return is a proper divergence whose
    optimum is flat across worlds, so the action gradient may self-extinguish.

OUTPUT  runs/_tier_b/c7_env_likelihood_bias/
"""
from __future__ import annotations
import argparse, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _common as C

# Substrates where every agent sees the whole public thread. p_env is
# observer-independent only here; see the derivation, section 3.
FULLY_OBSERVED = {
    "study_group", "study_group_strathearn", "study_group_ashbourne_gc",
    "study_group_strathearn_server", "inner_loop", "margin_notes",
    "conjecture_inn", "robotic_athanor",
}
PARTIALLY_OBSERVED = {"ashbourne_school"}   # fog of war — refuse


def build_parser():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    p.add_argument("--run", required=True, help="run directory, relative to repo root")
    p.add_argument("--iters", type=int, nargs="+", default=[25, 100, 200, 300],
                   help="checkpoints to measure at")
    p.add_argument("-K", type=int, default=8,
                   help="private prefixes sampled per post; higher K reduces the "
                        "Jensen bias that inflates beta_hat")
    p.add_argument("--max-posts", type=int, default=64,
                   help="posts per checkpoint, sampled without replacement")
    p.add_argument("--dry-run", action="store_true",
                   help="validate inputs and print the plan without loading a model")
    return p


def plan(args):
    """Everything checkable without a GPU. Run this first."""
    recs = C.load_metrics(args.run)
    if not recs:
        raise SystemExit(f"no metrics.jsonl under {args.run}")
    env = C.env_of(recs)
    if env in PARTIALLY_OBSERVED:
        raise SystemExit(
            f"{env} is partially observed (fog of war). p_env is observer-specific "
            f"there and this estimator does not apply — see section 3 of "
            f"environment_likelihood_derivation.md.")
    if env not in FULLY_OBSERVED:
        raise SystemExit(f"{env} not in the full-observability list; add it "
                         f"deliberately after checking the substrate.")
    cfg = json.load(open(os.path.join(C.ROOT, args.run, "config.json")))
    n_agents = len(cfg.get("character_prompts") or {})
    ck = os.path.join(C.ROOT, args.run, "checkpoints")
    have = sorted(int(d.split("_")[1]) for d in os.listdir(ck)
                  if d.startswith("iter_")) if os.path.isdir(ck) else []
    want = [i for i in args.iters if i in have]
    if not want:
        raise SystemExit(f"none of {args.iters} in available checkpoints {have}")

    passes = len(want) * args.max_posts * args.K
    pairs = len(want) * args.max_posts * args.K * max(1, n_agents - 1)
    print(f"run          {args.run}")
    print(f"substrate    {env}  (fully observed)")
    print(f"model        {cfg.get('model_name_or_path')}   agents {n_agents}")
    print(f"checkpoints  {want}")
    print(f"K            {args.K}")
    print(f"\ngenerate-and-score passes: {passes}")
    print(f"  the same figure if p_env were observer-specific: {pairs} "
          f"({max(1, n_agents-1)}x more)")
    print(f"  the saving is section 3 of the derivation: the correction is a "
          f"property of\n  the generator's turn, so it is computed once per post "
          f"and reused by every observer.")
    return {"run": args.run, "env": env, "iters": want, "K": args.K,
            "n_agents": n_agents, "passes": passes}


def main():
    args = build_parser().parse_args()
    out = C.outdir("c7_env_likelihood_bias")
    p = plan(args)
    json.dump(p, open(os.path.join(out, "plan.json"), "w"), indent=1)
    if args.dry_run:
        print("\n--dry-run: stopping before the GPU pass.")
        return
    raise SystemExit(
        "\nThe scoring pass is not implemented. It needs, per checkpoint:\n"
        "  * load the shared frozen base once; swap adapters per agent\n"
        "  * for each delivered post, rebuild the generator's context with its\n"
        "    private prefix removed, sample K continuations to the <post> tag,\n"
        "    and score the delivered STRING under each\n"
        "  * report beta_hat against pre-post length and the per-span entropy,\n"
        "    stratified by whether the realised private region is degenerate\n"
        "Predictions P1-P4 are fixed in this file's docstring and must not be\n"
        "edited after the first number exists.")


if __name__ == "__main__":
    main()
